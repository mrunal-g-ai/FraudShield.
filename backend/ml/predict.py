"""
FraudShield Inference Engine
Provides single-transaction scoring, batch CSV processing, risk-level categorization,
and human-interpretable risk explanation.
"""

from typing import Dict, Any, List, Optional
from pathlib import Path
import joblib
import numpy as np
import pandas as pd
from backend.ml.preprocessing import FEATURE_COLUMNS, PCA_FEATURES, TIME_FEATURE, AMOUNT_FEATURE

MODELS_DIR = Path(__file__).resolve().parent.parent / "models"
BEST_MODEL_PATH = MODELS_DIR / "best_model.joblib"


class FraudPredictor:
    _instance: Optional["FraudPredictor"] = None
    _pipeline = None

    def __init__(self):
        self.load_model()

    @classmethod
    def get_instance(cls) -> "FraudPredictor":
        if cls._instance is None:
            cls._instance = FraudPredictor()
        return cls._instance

    def load_model(self):
        if BEST_MODEL_PATH.exists():
            self._pipeline = joblib.load(BEST_MODEL_PATH)
        else:
            self._pipeline = None

    @property
    def is_loaded(self) -> bool:
        return self._pipeline is not None

    def predict_single(self, feature_dict: Dict[str, float], threshold: float = 0.5) -> Dict[str, Any]:
        """
        Runs inference on a single transaction dictionary containing Time, V1-V28, and Amount.
        """
        if not self.is_loaded:
            raise RuntimeError("Model artifact not found. Please train or initialize the model first.")

        df = pd.DataFrame([feature_dict])

        # Verify all feature columns
        for col in FEATURE_COLUMNS:
            if col not in df.columns:
                raise ValueError(f"Missing required feature: '{col}'")

        proba = self._pipeline.predict_proba(df[FEATURE_COLUMNS])[0]
        # Probability of class 1 (Fraud)
        fraud_prob = float(proba[1])
        predicted_class = 1 if fraud_prob >= threshold else 0

        # Risk level categorization
        if fraud_prob >= 0.70:
            risk_level = "HIGH"
        elif fraud_prob >= 0.35:
            risk_level = "MEDIUM"
        else:
            risk_level = "LOW"

        # Risk explanation & key feature indicators
        explanation, risk_factors = self._generate_explanation(feature_dict, fraud_prob, predicted_class)

        return {
            "predicted_class": predicted_class,
            "is_fraud": bool(predicted_class == 1),
            "risk_score": round(fraud_prob, 4),
            "risk_percentage": round(fraud_prob * 100, 2),
            "risk_level": risk_level,
            "confidence": round(float(np.max(proba)), 4),
            "threshold_used": threshold,
            "explanation": explanation,
            "risk_factors": risk_factors,
            "disclaimer": "This prediction is a probabilistic decision-support estimation generated by an academic machine learning model and does not constitute a guaranteed fraud classification."
        }

    def predict_batch(self, df: pd.DataFrame, threshold: float = 0.5) -> pd.DataFrame:
        """
        Runs batch prediction on a validated DataFrame containing FEATURE_COLUMNS.
        Returns the original DataFrame enriched with:
        - risk_score
        - predicted_class
        - risk_level
        """
        if not self.is_loaded:
            raise RuntimeError("Model artifact not found. Please train or initialize the model first.")

        probas = self._pipeline.predict_proba(df[FEATURE_COLUMNS])[:, 1]
        results_df = df.copy()
        results_df["risk_score"] = np.round(probas, 4)
        results_df["predicted_class"] = (probas >= threshold).astype(int)
        results_df["risk_level"] = np.where(
            probas >= 0.70, "HIGH",
            np.where(probas >= 0.35, "MEDIUM", "LOW")
        )
        return results_df

    def _generate_explanation(self, features: Dict[str, float], prob: float, is_fraud: int) -> tuple[str, List[Dict[str, Any]]]:
        """
        Synthesizes an interpretable risk summary by examining key predictive features
        (V14, V12, V10, V17 negative shifts, and V4, V11 positive shifts, Amount anomalies).
        """
        factors = []

        # Check key negative-shifted features
        for feat, name in [("V14", "Identity/Behavioral Index (V14)"),
                           ("V12", "Account Velocity Vector (V12)"),
                           ("V10", "Transaction Context Vector (V10)"),
                           ("V17", "Authorization Deviation (V17)")]:
            val = features.get(feat, 0.0)
            if val < -2.5:
                factors.append({
                    "feature": feat,
                    "label": name,
                    "value": round(val, 3),
                    "impact": "HIGH_RISK_NEGATIVE_DIVERGENCE",
                    "description": f"{feat} shows extreme negative deviation ({val:.2f}) strongly characteristic of fraudulent authorization."
                })

        # Check positive-shifted features
        for feat, name in [("V4", "Card Frequency Shift (V4)"),
                           ("V11", "Terminal Inconsistency Vector (V11)")]:
            val = features.get(feat, 0.0)
            if val > 2.0:
                factors.append({
                    "feature": feat,
                    "label": name,
                    "value": round(val, 3),
                    "impact": "HIGH_RISK_POSITIVE_SPIKE",
                    "description": f"{feat} exhibits an abnormal positive spike ({val:.2f}) aligning with suspicious transaction bursts."
                })

        amount = features.get(AMOUNT_FEATURE, 0.0)
        if amount > 1500.0:
            factors.append({
                "feature": "Amount",
                "label": "High Transaction Amount",
                "value": round(amount, 2),
                "impact": "ELEVATED_FINANCIAL_EXPOSURE",
                "description": f"Transaction amount (${amount:,.2f}) significantly exceeds median retail transaction volumes."
            })

        if is_fraud:
            if factors:
                summary = f"Flagged as Potentially Fraudulent (Risk Score: {prob*100:.1f}%). Primary risk drivers include {len(factors)} significant statistical anomalies across PCA velocity vectors and authorization parameters."
            else:
                summary = f"Flagged as Potentially Fraudulent (Risk Score: {prob*100:.1f}%). The model detected a compound non-linear pattern correlating with known fraudulent signatures."
        else:
            if prob < 0.15:
                summary = f"Classified as Likely Legitimate (Risk Score: {prob*100:.1f}%). All behavioral and authorization features align within standard baseline distribution bounds."
            else:
                summary = f"Classified as Low-to-Moderate Risk (Risk Score: {prob*100:.1f}%). Within acceptable operating tolerances, though minor feature variations were recorded."

        return summary, factors
